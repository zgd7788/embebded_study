#ifndef BUZZER_H
#define BUZZER_H

/*
    FS-MP1A 扩展板 SP1：PB6 / AF2 / TIM4_CH1，高电平驱动晶体管。
    本模块占用 PB6 和 TIM4 的计数基础，调用方不得并发改动这些资源。
    固定约 2kHz、50% 占空比，依赖 README 中已核对的约 208.878MHz
    TIM4 内核时钟；当前不提供运行中改频接口。
*/

/*
    功能：初始化固定音调，完成后保持静音、PB6 输出低
          调用前须开启 GPIOB/TIM4 时钟并独占 PB6/TIM4；重复初始化会重置 TIM4
    参数：无；内部固定使用 PB6/AF2/TIM4_CH1，约 2kHz、50% 占空比
    返回值：成功返回 0；底层定时器配置失败返回 -1
*/
int Buzzer_Init(void);

/*
    功能：开启 PWM 并将 PB6 配为 AF2，开始发声
          须先成功初始化并保持时钟开启；可重复调用，首段脉冲不保证完整
    参数：无
    返回值：成功返回 0；底层 PWM 启动失败返回 -1；尚未初始化返回 -2
*/
int Buzzer_Start(void);

/*
    功能：关闭 CH1 并将 PB6 切为普通推挽输出低，停止发声，不停止 TIM4 计数
          须先成功初始化并保持时钟开启；可重复调用
    参数：无
    返回值：成功返回 0；底层关闭通道失败返回 -1，仍尝试将 PB6 输出低；
            尚未初始化返回 -2，不操作寄存器
*/
int Buzzer_Stop(void);

#endif
